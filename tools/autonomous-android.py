#!/usr/bin/env python3
"""Trusted boundaries for the autonomous upstream Android workflow."""
import argparse
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PREFIX = "shared/src/commonMain/kotlin/io/github/gccammelli/meowstache/"
APP = "app/build.gradle.kts"
GENERATED = ["tools/upstream-lr4.json", "tools/local-mock/mock-lr4.yaml",
             "shared/src/commonTest/kotlin/io/github/gccammelli/meowstache/UpstreamLr4Contract.kt"]
ALLOWED = {PREFIX + name for name in (
    "HomeAssistant.kt", "DemoLocal.kt", "Models.kt", "ui/Robot.kt", "ui/Main.kt",
)} | set(GENERATED) | {APP, "docs/upstream-lr4.md",
    "shared/src/commonTest/kotlin/io/github/gccammelli/meowstache/UpstreamCompatibilityTest.kt"}
ADDITIVE_TEST = "shared/src/commonTest/kotlin/io/github/gccammelli/meowstache/UpstreamCompatibilityTest.kt"
MANUAL_REVIEW = {PREFIX + name for name in (
    "HomeAssistant.kt", "DemoLocal.kt", "Models.kt", "ui/Robot.kt", "ui/Main.kt",
)} | {ADDITIVE_TEST}


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT)


def bumped(text):
    text, count = re.subn(r"versionCode = (\d+)", lambda m: f"versionCode = {int(m[1])+1}", text)
    if count != 1:
        raise ValueError("Expected one Android versionCode")
    def name(m):  # 1.1.0-beta16 → 1.1.0-beta17; after a release, 1.1.0 → 1.1.1-beta1
        major, minor, patch, beta = m[1], m[2], int(m[3]), m[4]
        return f'versionName = "{major}.{minor}.{patch}-beta{int(beta)+1}"' if beta else f'versionName = "{major}.{minor}.{patch+1}-beta1"'
    text, count = re.subn(r'versionName = "(\d+)\.(\d+)\.(\d+)(?:-beta(\d+))?"', name, text)
    if count != 1:
        raise ValueError("Expected one Android versionName like 1.2.3 or 1.2.3-beta4")
    return text


DROPPED = []
DOC = "docs/upstream-lr4.md"
DOC_FALLBACK = "\n\n> The agent's release notes were malformed and were dropped; see the workflow run.\n"


def sanitized(patch, drop_source=False):
    """Return (text, headers). Model-written diffs are sometimes malformed (a hunk line missing its
    prefix). Generated files and the version are regenerated independently and the release notes
    have a fallback, so a chunk for those that does not apply is dropped; any other chunk that does
    not apply still fails the run."""
    text = Path(patch).read_text()
    chunks = re.split(r"(?m)^(?=diff --git )", text)
    kept, headers = [], set()
    for chunk in chunks:
        m = re.match(r"diff --git a/(\S+) b/", chunk)
        if not m:
            kept.append(chunk)
            continue
        path = m[1]
        headers.add(path)
        with tempfile.NamedTemporaryFile("w", suffix=".diff") as f:
            f.write(chunk)
            f.flush()
            err = subprocess.run(["git", "apply", "--check", f.name], cwd=ROOT, capture_output=True, text=True).stderr
        malformed = bool(err) and not any(k in err for k in ("does not apply", "patch failed", "No such file", "does not exist"))
        # A corrupt chunk (not parseable at all) can never be applied, so it is dropped for every
        # path and every caller; a well-formed chunk that merely does not apply is dropped only by apply().
        stale_source = bool(err) and path not in set(GENERATED + [APP, DOC, ADDITIVE_TEST]) and (malformed or drop_source)
        if stale_source:
            print(f"warning: dropped a source hunk that is corrupt or does not apply: {path}")
            if path not in DROPPED:
                DROPPED.append(path)
        if not (malformed and path in set(GENERATED + [APP, DOC]) or path == DOC and err or stale_source):
            kept.append(chunk)
    return "".join(kept), headers


def allowed_patch(patch):
    text, headers = sanitized(patch)
    with tempfile.NamedTemporaryFile("w", suffix=".diff") as f:
        f.write(text)
        f.flush()
        records = subprocess.check_output(["git", "apply", "--numstat", "-z", f.name], cwd=ROOT).split(b"\0")
    paths = []
    for record in filter(None, records):
        additions, deletions, path = record.decode().split("\t", 2)
        if path not in ALLOWED or not additions.isdigit() or not deletions.isdigit():
            raise ValueError(f"Agent patch changes a protected path or binary file: {path}")
        if path == ADDITIVE_TEST and int(deletions):
            raise ValueError("Existing upstream compatibility assertions may not be removed")
        paths.append(path)
    # The firmware lock, fixture and mock pin are regenerated by apply() and the agent's hunks for them
    # are dropped anyway, so the candidate only has to carry the version and release notes.
    if not {APP, DOC} <= set(paths) | headers:
        raise ValueError("Candidate must update the version and release notes")


def auto_merge_safe(patch):
    text, _ = sanitized(patch)
    with tempfile.NamedTemporaryFile("w", suffix=".diff") as f:
        f.write(text)
        f.flush()
        records = subprocess.check_output(["git", "apply", "--numstat", "-z", f.name], cwd=ROOT).split(b"\0")
    changed = {record.decode().split("\t", 2)[2] for record in filter(None, records)}
    blocked = sorted(changed & MANUAL_REVIEW)
    if blocked:
        raise ValueError("Runtime networking or UI changes require maintainer review: " + ", ".join(blocked))
    print("Candidate is within the non-UI auto-merge tier")


def apply(patch, tag):
    if git("status", "--porcelain", "--untracked-files=no").strip():
        raise ValueError("Candidate validation requires a clean checkout")
    allowed_patch(patch)
    # The version bump and upstream evidence are regenerated here, independently of the agent,
    # and are authoritative. The agent's hunks for those files are dropped instead of applied:
    # a model-written diff of generated files often fails to apply (it did every night from
    # 2026-11-18), and an agent can't forge evidence this way either.
    subprocess.run(["python3", "tools/upstream-lr4.py", "--update", "--tag", tag], cwd=ROOT, check=True)
    (ROOT / APP).write_text(bumped((ROOT / APP).read_text()))
    skipped = [f"--exclude={path}" for path in GENERATED + [APP]]
    # A source hunk that does not apply is dropped too (the agent wrote it against stale context);
    # the contract tests, the emulator smoke test and the independent review still gate the PR.
    text, headers = sanitized(patch, drop_source=True)
    with tempfile.NamedTemporaryFile("w", suffix=".diff") as f:
        f.write(text)
        f.flush()
        subprocess.run(["git", "apply", "--index", *skipped, f.name], cwd=ROOT, check=True)
    if DOC in headers and f"a/{DOC}" not in text:
        (ROOT / DOC).write_text((ROOT / DOC).read_text().rstrip("\n") + DOC_FALLBACK)
        subprocess.run(["git", "add", "--", DOC], cwd=ROOT, check=True)
    if DROPPED:
        note = "\n\n> Maintainer review needed: the agent's changes to " + ", ".join(sorted(set(DROPPED))) + \
               " did not apply and were dropped; the upstream evidence and version were regenerated only.\n"
        (ROOT / DOC).write_text((ROOT / DOC).read_text().rstrip("\n") + note)
        subprocess.run(["git", "add", "--", DOC], cwd=ROOT, check=True)
    for line in git("diff", "--cached", "--raw").decode().splitlines():
        if line.split()[1] != "100644":
            raise ValueError("Candidate must contain regular source files; deletion/symlink changes are blocked")
    subprocess.run(["git", "add", "--", *GENERATED, APP], cwd=ROOT, check=True)
    print("Candidate patch scope applied; version and upstream evidence regenerated independently")


def sanitize_for_review(patch):
    """Rewrite the candidate as the patch that validate/publish will actually apply, so the
    independent review judges what lands. Dropped hunks are listed in a preamble git ignores."""
    text, _ = sanitized(patch, drop_source=True)
    dropped = sorted(set(DROPPED))
    preamble = ("NOTE: hunks that were corrupt or did not apply were dropped before review"
                + (": " + ", ".join(dropped) if dropped else "")
                + ". Version, upstream evidence and (if its hunk was bad) release notes are regenerated independently.\n")
    Path(patch).write_text(preamble + text)


def self_test():
    value = 'versionCode = 20\nversionName = "1.1.0-beta16"\n'
    assert bumped(value) == 'versionCode = 21\nversionName = "1.1.0-beta17"\n'
    assert bumped('versionCode = 21\nversionName = "1.1.0"\n') == 'versionCode = 22\nversionName = "1.1.1-beta1"\n'
    assert ".github/workflows/build.yml" not in ALLOWED
    assert "tools/android-smoke.py" not in ALLOWED
    def diff(path):
        return f"diff --git a/{path} b/{path}\n--- a/{path}\n+++ b/{path}\n@@ -1 +1 @@\n-before\n+after\n"
    with tempfile.TemporaryDirectory() as work:
        patch = Path(work) / "candidate.diff"
        valid = "".join(diff(path) for path in GENERATED + [APP, "docs/upstream-lr4.md"])
        patch.write_text(valid)
        allowed_patch(patch)
        auto_merge_safe(patch)
        for path in (".github/workflows/build.yml", "tools/android-smoke.py",
                     PREFIX + "Repo.kt", "shared/src/commonTest/kotlin/io/github/gccammelli/meowstache/LocalModeTest.kt"):
            patch.write_text(valid + diff(path))
            try:
                allowed_patch(patch)
            except ValueError:
                pass
            else:
                raise AssertionError(f"Protected path was accepted: {path}")
        patch.write_text(valid + diff(ADDITIVE_TEST))
        try:
            allowed_patch(patch)
        except ValueError:
            pass
        else:
            raise AssertionError("Existing upstream assertions could be removed")
        patch.write_text(diff(PREFIX + "HomeAssistant.kt"))
        try:
            allowed_patch(patch)
        except ValueError:
            pass
        else:
            raise AssertionError("Incomplete upstream evidence was accepted")
        patch.write_text(valid + diff(PREFIX + "HomeAssistant.kt"))
        try:
            auto_merge_safe(patch)
        except ValueError:
            pass
        else:
            raise AssertionError("Sensitive runtime change was accepted for auto-merge")
    print("Autonomous workflow boundary self-test passed")


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser("bump")
    sub.add_parser("self-test")
    check = sub.add_parser("apply")
    check.add_argument("patch", type=Path)
    check.add_argument("--tag", required=True)
    san = sub.add_parser("sanitize")
    san.add_argument("patch", type=Path)
    patch_check = sub.add_parser("check-patch")
    patch_check.add_argument("patch", type=Path)
    merge_check = sub.add_parser("auto-merge-safe")
    merge_check.add_argument("patch", type=Path)
    args = parser.parse_args()
    if args.action == "bump":
        (ROOT / APP).write_text(bumped((ROOT / APP).read_text()))
    elif args.action == "apply":
        apply(args.patch.resolve(), args.tag)
    elif args.action == "sanitize":
        sanitize_for_review(args.patch.resolve())
    elif args.action == "check-patch":
        allowed_patch(args.patch.resolve())
    elif args.action == "auto-merge-safe":
        auto_merge_safe(args.patch.resolve())
    else:
        self_test()


if __name__ == "__main__":
    main()
